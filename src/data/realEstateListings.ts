export const formatPrice = (price: number, type: string, lang: string) => {
  const formatted = price.toLocaleString(lang === "he" ? "he-IL" : "en-IL");
  if (type === "rent") {
    return lang === "he" ? `₪${formatted}/חודש` : `₪${formatted}/mo`;
  }
  return `₪${formatted}`;
};
